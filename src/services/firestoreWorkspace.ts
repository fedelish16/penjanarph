export function createEmptyClientWorkspace(): TeacherWorkspaceState {
  return {
    documents: [],
    timetable: [],
    rptEntries: [],
    syllabi: [],
    classConfigs: {},
    automation: {
      autoGenerateDaily: true,
      tarikhMulaPenggal: new Date().toISOString().slice(0, 10),
      mingguSemasa: 12,
      templatRph:
        'Standard KPM / PPD (Objektif, KK, Aktiviti, BBM, EMK, KBAT, Pentaksiran, Pembezaan, Refleksi)',
      catatanGuruUmum: '',
      schoolFormat: {
        namaSekolah: '',
        namaGuru: '',
        tajukRph: 'Rancangan Pengajaran Harian (RPH)',
        sertakanTandatanganPk: true,
      },
    },
    dailyDrafts: {},
  };
}

export function sanitizeId(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 128);
  return cleaned || `id_${Date.now()}`;
}

export async function ensureTeacherProfile(user: User): Promise<void> {
  const profilePath = `teachers/${user.uid}`;
  const ref = doc(db, 'teachers', user.uid);

  try {
    const snap = await getDoc(ref);
    const displayName = (user.displayName || 'Guru PelanRPH').slice(0, 160);
    const email = (user.email || '').slice(0, 254);

    if (!snap.exists()) {
      await setDoc(ref, {
        uid: user.uid,
        displayName,
        email,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    } else {
      await updateDoc(ref, {
        displayName,
        email,
        updatedAt: serverTimestamp(),
      });
    }
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, profilePath);
  }
}

export function subscribeWorkspace(
  uid: string,
  onData: (ws: Omit<TeacherWorkspaceState, 'dailyDrafts'> | null) => void,
  onError: (err: Error) => void
): () => void {
  const wsPath = `teachers/${uid}/workspaces/main`;
  const ref = doc(db, 'teachers', uid, 'workspaces', 'main');

  return onSnapshot(
    ref,
    (snapshot) => {
      if (!snapshot.exists()) {
        onData(null);
        return;
      }
      const data = snapshot.data();
      onData({
        documents: Array.isArray(data.documents) ? data.documents : [],
        timetable: Array.isArray(data.timetable) ? data.timetable : [],
        rptEntries: Array.isArray(data.rptEntries) ? data.rptEntries : [],
        syllabi: Array.isArray(data.syllabi) ? data.syllabi : [],
        classConfigs:
          data.classConfigs && typeof data.classConfigs === 'object'
            ? data.classConfigs
            : {},
        automation:
          data.automation && typeof data.automation === 'object'
            ? data.automation
            : createEmptyClientWorkspace().automation,
      });
    },
    (error) => {
      try {
        handleFirestoreError(error, OperationType.GET, wsPath);
      } catch (wrapped) {
        onError(
          wrapped instanceof Error ? wrapped : new Error(String(wrapped))
        );
      }
    }
  );
}

function stripUndefined<T>(value: T): T {
  if (value === null || typeof value !== 'object') {
    return value;
  }
  if (Array.isArray(value)) {
    return value.map((item) => stripUndefined(item)) as unknown as T;
  }
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
    if (v !== undefined) {
      out[k] = stripUndefined(v);
    }
  }
  return out as T;
}

export async function saveWorkspaceToCloud(
  uid: string,
  ws: TeacherWorkspaceState
): Promise<void> {
  const wsPath = `teachers/${uid}/workspaces/main`;
  const ref = doc(db, 'teachers', uid, 'workspaces', 'main');

  // Defensive bounds matching firebase-blueprint.json & firestore.rules
  const safeDocuments = stripUndefined((ws.documents ?? []).slice(0, 50));
  const safeTimetable = stripUndefined((ws.timetable ?? []).slice(0, 150));
  const safeRptEntries = stripUndefined((ws.rptEntries ?? []).slice(0, 300));
  const safeSyllabi = stripUndefined((ws.syllabi ?? []).slice(0, 50));
  const safeClassConfigs = stripUndefined(
    Object.fromEntries(Object.entries(ws.classConfigs ?? {}).slice(0, 60))
  );
  const safeAutomation = stripUndefined(
    ws.automation ?? createEmptyClientWorkspace().automation
  );

  try {
    const existingSnap = await getDoc(ref);
    if (!existingSnap.exists()) {
      await setDoc(ref, {
        uid,
        documents: safeDocuments,
        timetable: safeTimetable,
        rptEntries: safeRptEntries,
        syllabi: safeSyllabi,
        classConfigs: safeClassConfigs,
        automation: safeAutomation,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    } else {
      await updateDoc(ref, {
        documents: safeDocuments,
        timetable: safeTimetable,
        rptEntries: safeRptEntries,
        syllabi: safeSyllabi,
        classConfigs: safeClassConfigs,
        automation: safeAutomation,
        updatedAt: serverTimestamp(),
      });
    }
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, wsPath);
  }
}

export function subscribeDailyDrafts(
  uid: string,
  onData: (draftsMap: Record<string, DailyAutoDraft>) => void,
  onError: (err: Error) => void
): () => void {
  const collPath = `teachers/${uid}/dailyDrafts`;
  const q = query(
    collection(db, 'teachers', uid, 'dailyDrafts'),
    where('uid', '==', uid)
  );

  return onSnapshot(
    q,
    (snapshot) => {
      const map: Record<string, DailyAutoDraft> = {};
      snapshot.forEach((docSnap) => {
        const d = docSnap.data() as DailyAutoDraft;
        map[docSnap.id] = d;
      });
      onData(map);
    },
    (error) => {
      try {
        handleFirestoreError(error, OperationType.LIST, collPath);
      } catch (wrapped) {
        onError(
          wrapped instanceof Error ? wrapped : new Error(String(wrapped))
        );
      }
    }
  );
}

export async function upsertDailyDraft(
  uid: string,
  entry: DailyAutoDraft
): Promise<void> {
  const safeId = sanitizeId(entry.id);
  const draftPath = `teachers/${uid}/dailyDrafts/${safeId}`;
  const ref = doc(db, 'teachers', uid, 'dailyDrafts', safeId);

  const payload = stripUndefined({
    minggu_rpt: (entry.minggu_rpt || '').slice(0, 40),
    slot: entry.slot,
    rptMatch: entry.rptMatch ?? null,
    requestInput: entry.requestInput,
    draft: entry.draft,
    teacherReflection: (entry.teacherReflection || '').slice(0, 4000),
    statusSemakan:
      entry.statusSemakan === 'disemak_guru' ? 'disemak_guru' : 'belum_disemak',
    generatedAt: (entry.generatedAt || new Date().toISOString()).slice(0, 64),
  });

  try {
    const existingSnap = await getDoc(ref);
    if (!existingSnap.exists()) {
      await setDoc(ref, {
        id: safeId,
        uid,
        date: (entry.date || '').slice(0, 20),
        ...payload,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    } else {
      await updateDoc(ref, {
        ...payload,
        updatedAt: serverTimestamp(),
      });
    }
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, draftPath);
  }
}

export function subscribeSavedDrafts(
  uid: string,
  onData: (entries: SavedRphEntry[]) => void,
  onError: (err: Error) => void
): () => void {
  const collPath = `teachers/${uid}/savedDrafts`;
  const q = query(
    collection(db, 'teachers', uid, 'savedDrafts'),
    where('uid', '==', uid)
  );

  return onSnapshot(
    q,
    (snapshot) => {
      const list: SavedRphEntry[] = [];
      snapshot.forEach((docSnap) => {
        const d = docSnap.data() as Omit<SavedRphEntry, 'createdAt'> & {
          createdAt?: { toDate?: () => Date } | string | null;
        };
        const createdIso =
          typeof d.createdAt === 'string'
            ? d.createdAt
            : d.createdAt && typeof d.createdAt.toDate === 'function'
              ? d.createdAt.toDate().toISOString()
              : new Date().toISOString();
        list.push({
          id: docSnap.id,
          createdAt: createdIso,
          input: d.input,
          draft: d.draft,
          teacherReflection: d.teacherReflection || '',
        });
      });
      list.sort((a, b) => b.createdAt.localeCompare(a.createdAt));
      onData(list);
    },
    (error) => {
      try {
        handleFirestoreError(error, OperationType.LIST, collPath);
      } catch (wrapped) {
        onError(
          wrapped instanceof Error ? wrapped : new Error(String(wrapped))
        );
      }
    }
  );
}

