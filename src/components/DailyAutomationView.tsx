import React, { useEffect, useMemo, useState } from 'react';
import {
  AlertCircle,
  Calendar,
  CheckCircle2,
  Clock,
  Loader2,
  RefreshCw,
  Sparkles,
  Upload,
} from 'lucide-react';
import { RphDocumentPreview } from './RphDocumentPreview';
import type {
  DailyAutoDraft,
  HariMinggu,
  RphDraftOutput,
  TeacherWorkspaceState,
  TimetableSlot,
} from '../types/rph';

interface DailyAutomationViewProps {
  workspace: TeacherWorkspaceState;
  selectedDate: string;
  onSelectDate: (date: string) => void;
  onWorkspaceUpdate: (next: TeacherWorkspaceState) => Promise<void>;
  onGenerateDaily: (params: {
    date: string;
    mingguNombor: number;
    forceRegenerate?: boolean;
    slotIds?: string[];
  }) => Promise<void>;
  onLoadDemoPack: () => Promise<void>;
  onGoToSetup: () => void;
  onSaveDraftToArchive: (entry: DailyAutoDraft) => void;
  isGeneratingDaily: boolean;
  dailyError: string | null;
}

const DAY_NAMES: HariMinggu[] = [
  'Ahad',
  'Isnin',
  'Selasa',
  'Rabu',
  'Khamis',
  'Jumaat',
  'Sabtu',
];

function getMalayDay(dateIso: string): HariMinggu {
  const parts = dateIso.split('-').map(Number);
  if (parts.length !== 3 || parts.some((n) => Number.isNaN(n))) return 'Isnin';
  const d = new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]));
  return DAY_NAMES[d.getUTCDay()] ?? 'Isnin';
}

function getWeekDatesForSelected(dateIso: string): Array<{
  date: string;
  day: HariMinggu;
}> {
  const parts = dateIso.split('-').map(Number);
  const base =
    parts.length === 3
      ? new Date(Date.UTC(parts[0], parts[1] - 1, parts[2]))
      : new Date();
  const dow = base.getUTCDay(); // 0=Sun..6=Sat
  const mondayOffset = dow === 0 ? -6 : 1 - dow;
  const monday = new Date(base);
  monday.setUTCDate(base.getUTCDate() + mondayOffset);

  const result: Array<{ date: string; day: HariMinggu }> = [];
  for (let i = 0; i < 5; i++) {
    const d = new Date(monday);
    d.setUTCDate(monday.getUTCDate() + i);
    const iso = d.toISOString().slice(0, 10);
    result.push({ date: iso, day: getMalayDay(iso) });
  }
  return result;
}

export const DailyAutomationView: React.FC<DailyAutomationViewProps> = ({
  workspace,
  selectedDate,
  onSelectDate,
  onWorkspaceUpdate,
  onGenerateDaily,
  onLoadDemoPack,
  onGoToSetup,
  onSaveDraftToArchive,
  isGeneratingDaily,
  dailyError,
}) => {
  const [selectedSlotId, setSelectedSlotId] = useState<string | null>(null);
  const [autoTriggeredKey, setAutoTriggeredKey] = useState<string>('');

  const hasDocuments =
    workspace.timetable.length > 0 && workspace.rptEntries.length > 0;

  const selectedDayName = getMalayDay(selectedDate);
  const weekDays = useMemo(
    () => getWeekDatesForSelected(selectedDate),
    [selectedDate]
  );

  const daySlots: TimetableSlot[] = useMemo(
    () =>
      workspace.timetable
        .filter((s) => s.hari === selectedDayName)
        .sort((a, b) => a.masa_mula.localeCompare(b.masa_mula)),
    [workspace.timetable, selectedDayName]
  );

  const availableWeeks = useMemo(() => {
    const nums = Array.from(
      new Set(workspace.rptEntries.map((r) => r.minggu_nombor))
    ).sort((a, b) => a - b);
    return nums.length > 0 ? nums : [workspace.automation.mingguSemasa || 12];
  }, [workspace.rptEntries, workspace.automation.mingguSemasa]);

  const activeMinggu = workspace.automation.mingguSemasa || availableWeeks[0] || 12;

  // Keep selectedSlotId valid when changing date
  useEffect(() => {
    if (daySlots.length === 0) {
      setSelectedSlotId(null);
      return;
    }
    if (!selectedSlotId || !daySlots.some((s) => s.id === selectedSlotId)) {
      setSelectedSlotId(daySlots[0].id);
    }
  }, [daySlots, selectedSlotId]);

  // Automatic daily generation when Auto-Jana Harian is enabled and day has ungenerated slots
  useEffect(() => {
    if (!hasDocuments || !workspace.automation.autoGenerateDaily) return;
    if (daySlots.length === 0 || isGeneratingDaily) return;

    const triggerSignature = `${selectedDate}_${activeMinggu}`;
    if (autoTriggeredKey === triggerSignature) return;

    const hasMissingDraft = daySlots.some(
      (slot) => !workspace.dailyDrafts[`${selectedDate}_${slot.id}`]
    );

    if (hasMissingDraft) {
      setAutoTriggeredKey(triggerSignature);
      void onGenerateDaily({
        date: selectedDate,
        mingguNombor: activeMinggu,
      });
    }
  }, [
    hasDocuments,
    workspace.automation.autoGenerateDaily,
    workspace.dailyDrafts,
    daySlots,
    selectedDate,
    activeMinggu,
    isGeneratingDaily,
    autoTriggeredKey,
    onGenerateDaily,
  ]);

  const activeSlot =
    daySlots.find((s) => s.id === selectedSlotId) ?? daySlots[0] ?? null;
  const activeDraftKey = activeSlot ? `${selectedDate}_${activeSlot.id}` : '';
  const activeDailyEntry: DailyAutoDraft | null = activeDraftKey
    ? workspace.dailyDrafts[activeDraftKey] ?? null
    : null;

  const handleToggleAutoDaily = async () => {
    await onWorkspaceUpdate({
      ...workspace,
      automation: {
        ...workspace.automation,
        autoGenerateDaily: !workspace.automation.autoGenerateDaily,
      },
    });
  };

  const handleChangeWeek = async (nextWeek: number) => {
    await onWorkspaceUpdate({
      ...workspace,
      automation: {
        ...workspace.automation,
        mingguSemasa: nextWeek,
      },
    });
  };

  const handleDraftInlineUpdate = async (updatedDraft: RphDraftOutput) => {
    if (!activeDailyEntry) return;
    const updatedEntry: DailyAutoDraft = {
      ...activeDailyEntry,
      draft: updatedDraft,
    };
    await onWorkspaceUpdate({
      ...workspace,
      dailyDrafts: {
        ...workspace.dailyDrafts,
        [activeDailyEntry.id]: updatedEntry,
      },
    });
  };

  const handleReflectionUpdate = async (val: string) => {
    if (!activeDailyEntry) return;
    const updatedEntry: DailyAutoDraft = {
      ...activeDailyEntry,
      teacherReflection: val,
    };
    await onWorkspaceUpdate({
      ...workspace,
      dailyDrafts: {
        ...workspace.dailyDrafts,
        [activeDailyEntry.id]: updatedEntry,
      },
    });
  };

  const handleToggleApproval = async () => {
    if (!activeDailyEntry) return;
    const nextStatus: DailyAutoDraft['statusSemakan'] =
      activeDailyEntry.statusSemakan === 'disemak_guru'
        ? 'belum_disemak'
        : 'disemak_guru';
    await onWorkspaceUpdate({
      ...workspace,
      dailyDrafts: {
        ...workspace.dailyDrafts,
        [activeDailyEntry.id]: {
          ...activeDailyEntry,
          statusSemakan: nextStatus,
        },
      },
    });
  };

  // First-time onboarding state when documents have not been uploaded yet
  if (!hasDocuments) {
    return (
      <div className="bg-white border border-slate-200 rounded-xl p-8 lg:p-10 space-y-6">
        <div className="max-w-2xl space-y-3">
          <p className="text-xs font-semibold text-sky-700">
            Automasi Harian · Jadual + RPT + Sukatan Pelajaran
          </p>
          <h2 className="text-2xl font-bold tracking-tight text-slate-900 text-balance">
            Muat naik dokumen pengajaran anda sekali, dan biarkan AI menjana
            cadangan RPH secara automatik setiap hari
          </h2>
          <p className="text-sm text-slate-600 leading-relaxed">
            Apabila anda memuat naik Jadual Mengajar, RPT tahunan, dan Sukatan
            Pelajaran (DSKP), PelanRPH akan memadankan kelas hari ini dengan
            minggu RPT semasa dan menyediakan semua draf RPH hari tersebut
            untuk semakan anda.
          </p>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-3 gap-4 border-t border-slate-200 pt-6">
          <div className="space-y-1">
            <div className="text-xs font-semibold text-slate-900">
              01. Jadual Mengajar
            </div>
            <p className="text-xs text-slate-500 leading-relaxed">
              Mengenal pasti hari, masa mula/tamat, tempoh minit, subjek dan
              kelas secara automatik.
            </p>
          </div>
          <div className="space-y-1">
            <div className="text-xs font-semibold text-slate-900">
              02. Rancangan Pengajaran Tahunan
            </div>
            <p className="text-xs text-slate-500 leading-relaxed">
              Memadankan Minggu RPT semasa serta menyalin tema, SK dan SP
              secara verbatim.
            </p>
          </div>
          <div className="space-y-1">
            <div className="text-xs font-semibold text-slate-900">
              03. Sukatan Pelajaran (DSKP)
            </div>
            <p className="text-xs text-slate-500 leading-relaxed">
              Membantu cadangan aktiviti, pentaksiran TP1–TP6, KBAT dan
              pembezaan yang tepat.
            </p>
          </div>
        </div>

        <div className="flex flex-wrap items-center gap-3 pt-2">
          <button
            type="button"
            onClick={onGoToSetup}
            className="inline-flex items-center gap-2 rounded-lg bg-sky-700 px-4 py-2.5 text-sm font-semibold text-white hover:bg-sky-800 transition-colors whitespace-nowrap"
          >
            <Upload className="w-4 h-4" />
            Muat Naik Dokumen Guru
          </button>
          <button
            type="button"
            onClick={() => void onLoadDemoPack()}
            className="inline-flex items-center gap-2 rounded-lg border border-slate-300 bg-white px-4 py-2.5 text-sm font-medium text-slate-800 hover:bg-slate-50 transition-colors whitespace-nowrap"
          >
            <Sparkles className="w-4 h-4 text-sky-700" />
            Cuba Set Dokumen Contoh Lengkap
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-5">
      {/* Daily Control Strip */}
      <div className="no-print bg-white border border-slate-200 rounded-xl p-4 flex flex-wrap items-center justify-between gap-4">
        <div className="flex flex-wrap items-center gap-3">
          {/* Date Picker */}
          <div className="flex items-center gap-2">
            <Calendar className="w-4 h-4 text-sky-700 shrink-0" />
            <input
              type="date"
              value={selectedDate}
              onChange={(e) => {
                setAutoTriggeredKey('');
                onSelectDate(e.target.value);
              }}
              aria-label="Tarikh PdPc"
              className="rounded-lg border border-slate-300 px-2.5 py-1.5 font-mono text-xs font-medium text-slate-900 tabular-nums focus:border-sky-700 focus:outline-none"
            />
          </div>

          {/* Weekday Segmented Control */}
          <div className="flex items-center gap-1 p-1 bg-slate-100 rounded-lg overflow-x-auto">
            {weekDays.map((item) => {
              const active = item.date === selectedDate;
              return (
                <button
                  key={item.date}
                  type="button"
                  onClick={() => {
                    setAutoTriggeredKey('');
                    onSelectDate(item.date);
                  }}
                  className={`px-2.5 py-1 text-xs font-medium rounded-md transition-colors whitespace-nowrap shrink-0 ${
                    active
                      ? 'bg-white text-slate-900 shadow-sm'
                      : 'text-slate-600 hover:text-slate-900'
                  }`}
                >
                  {item.day}
                </button>
              );
            })}
          </div>

          {/* Active RPT Week Selector */}
          <div className="flex items-center gap-2">
            <label
              htmlFor="active-rpt-week"
              className="text-xs font-medium text-slate-600 whitespace-nowrap"
            >
              Minggu RPT:
            </label>
            <select
              id="active-rpt-week"
              value={activeMinggu}
              onChange={(e) => {
                setAutoTriggeredKey('');
                void handleChangeWeek(Number(e.target.value));
              }}
              className="rounded-lg border border-slate-300 bg-white px-2.5 py-1.5 font-mono text-xs font-semibold text-slate-900 focus:border-sky-700 focus:outline-none"
            >
              {availableWeeks.map((wk) => {
                const sampleEntry = workspace.rptEntries.find(
                  (r) => r.minggu_nombor === wk
                );
                const isExam =
                  sampleEntry &&
                  !sampleEntry.standard_kandungan &&
                  sampleEntry.tema;
                return (
                  <option key={wk} value={wk}>
                    Minggu {wk}
                    {isExam ? ` (${sampleEntry.tema})` : ''}
                  </option>
                );
              })}
            </select>
          </div>
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          <button
            type="button"
            onClick={() => void handleToggleAutoDaily()}
            className={`inline-flex items-center gap-1.5 rounded-lg border px-3 py-1.5 text-xs font-medium transition-colors whitespace-nowrap ${
              workspace.automation.autoGenerateDaily
                ? 'border-emerald-300 bg-emerald-50 text-emerald-900'
                : 'border-slate-300 bg-white text-slate-600'
            }`}
          >
            <CheckCircle2 className="w-3.5 h-3.5" />
            Auto-Jana Harian:{' '}
            {workspace.automation.autoGenerateDaily ? 'Aktif' : 'Manual'}
          </button>

          <button
            type="button"
            disabled={isGeneratingDaily || daySlots.length === 0}
            onClick={() =>
              void onGenerateDaily({
                date: selectedDate,
                mingguNombor: activeMinggu,
                forceRegenerate: true,
              })
            }
            className="inline-flex items-center gap-1.5 rounded-lg bg-sky-700 px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-sky-800 disabled:opacity-50 transition-colors whitespace-nowrap"
          >
            {isGeneratingDaily ? (
              <>
                <Loader2 className="w-3.5 h-3.5 animate-spin" />
                Menjana Slot Hari Ini...
              </>
            ) : (
              <>
                <RefreshCw className="w-3.5 h-3.5" />
                Jana Semula Hari Ini
              </>
            )}
          </button>
        </div>
      </div>

      {dailyError && (
        <div className="no-print rounded-xl border border-red-200 bg-red-50 px-4 py-3 text-xs text-red-800 flex items-center gap-2">
          <AlertCircle className="w-4 h-4 text-red-600 shrink-0" />
          <span>{dailyError}</span>
        </div>
      )}

      {/* Main 2-Column Daily Queue + Review Workspace */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
        {/* Left: Today's Class Queue */}
        <div className="no-print lg:col-span-4 bg-white border border-slate-200 rounded-xl divide-y divide-slate-200">
          <div className="p-4 flex items-center justify-between gap-2">
            <div>
              <h2 className="text-sm font-semibold text-slate-900">
                Jadual Kelas · {selectedDayName}
              </h2>
              <p className="text-xs text-slate-500 font-mono tabular-nums mt-0.5">
                {selectedDate} · Minggu {activeMinggu} · {daySlots.length} sesi
              </p>
            </div>
            <button
              type="button"
              onClick={onGoToSetup}
              className="text-xs font-medium text-sky-700 hover:underline whitespace-nowrap"
            >
              Urus Jadual
            </button>
          </div>

          {daySlots.length === 0 ? (
            <div className="p-6 text-center space-y-2">
              <p className="text-sm font-medium text-slate-900">
                Tiada sesi mengajar pada hari {selectedDayName}
              </p>
              <p className="text-xs text-slate-500">
                Pilih hari persekolahan lain (Isnin–Jumaat) di atas atau tambah
                slot waktu dalam Dokumen &amp; Jadual.
              </p>
            </div>
          ) : (
            <div className="divide-y divide-slate-200">
              {daySlots.map((slot) => {
                const entry = workspace.dailyDrafts[`${selectedDate}_${slot.id}`];
                const isSelected = activeSlot?.id === slot.id;

                return (
                  <div
                    key={slot.id}
                    className={`p-4 transition-colors ${
                      isSelected ? 'bg-sky-50/60' : 'hover:bg-slate-50/70'
                    }`}
                  >
                    <button
                      type="button"
                      onClick={() => setSelectedSlotId(slot.id)}
                      className="w-full text-left space-y-2"
                    >
                      <div className="flex items-center justify-between gap-2 text-xs">
                        <span className="font-mono font-semibold text-slate-900 tabular-nums">
                          {slot.masa_mula} – {slot.masa_tamat}
                        </span>
                        <span className="font-mono text-slate-500 tabular-nums flex items-center gap-1">
                          <Clock className="w-3 h-3" />
                          {slot.tempoh_minit} minit
                        </span>
                      </div>

                      <div>
                        <div className="text-sm font-semibold text-slate-900">
                          {slot.mata_pelajaran}
                        </div>
                        <div className="text-xs text-slate-600">
                          {slot.kelas}
                          {slot.bilik ? ` · ${slot.bilik}` : ''}
                        </div>
                      </div>

                      {/* Explicit icon + text status */}
                      <div className="flex items-center justify-between gap-2 pt-1 text-xs">
                        {isGeneratingDaily && !entry ? (
                          <span className="inline-flex items-center gap-1.5 text-sky-700 font-medium">
                            <Loader2 className="w-3.5 h-3.5 animate-spin" />
                            Sedang menjana draf...
                          </span>
                        ) : !entry ? (
                          <span className="text-slate-500">
                            Menunggu penjanaan
                          </span>
                        ) : entry.draft.status === 'PERLU_MAKLUMAT' ? (
                          <span className="inline-flex items-center gap-1.5 text-amber-700 font-medium">
                            <AlertCircle className="w-3.5 h-3.5" />
                            PERLU_MAKLUMAT
                          </span>
                        ) : entry.statusSemakan === 'disemak_guru' ? (
                          <span className="inline-flex items-center gap-1.5 text-emerald-700 font-semibold">
                            <CheckCircle2 className="w-3.5 h-3.5" />
                            SIAP · Disemak Guru
                          </span>
                        ) : (
                          <span className="inline-flex items-center gap-1.5 text-sky-800 font-medium">
                            <CheckCircle2 className="w-3.5 h-3.5" />
                            SIAP · Perlu Semakan Guru
                          </span>
                        )}
                      </div>
                    </button>

                    {entry && (
                      <div className="mt-2 pt-2 border-t border-slate-100 flex items-center justify-end">
                        <button
                          type="button"
                          disabled={isGeneratingDaily}
                          onClick={() =>
                            void onGenerateDaily({
                              date: selectedDate,
                              mingguNombor: activeMinggu,
                              forceRegenerate: true,
                              slotIds: [slot.id],
                            })
                          }
                          className="text-[11px] font-medium text-slate-500 hover:text-sky-700 transition-colors"
                        >
                          Jana semula slot ini
                        </button>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
          )}
        </div>

        {/* Right: Active Slot RPH Review & Edit Canvas */}
        <div className="lg:col-span-8 print-only-full space-y-3">
          {activeDailyEntry && activeDailyEntry.draft.status === 'SIAP' && (
            <div className="no-print bg-white border border-slate-200 rounded-xl px-4 py-3 flex flex-wrap items-center justify-between gap-3">
              <div className="text-xs text-slate-600">
                Cadangan automatik untuk{' '}
                <span className="font-semibold text-slate-900">
                  {activeDailyEntry.slot.mata_pelajaran} ·{' '}
                  {activeDailyEntry.slot.kelas}
                </span>{' '}
                ({activeDailyEntry.minggu_rpt})
              </div>
              <button
                type="button"
                onClick={() => void handleToggleApproval()}
                className={`inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 text-xs font-semibold transition-colors whitespace-nowrap ${
                  activeDailyEntry.statusSemakan === 'disemak_guru'
                    ? 'bg-emerald-600 text-white hover:bg-emerald-700'
                    : 'border border-slate-300 bg-white text-slate-800 hover:bg-slate-50'
                }`}
              >
                <CheckCircle2 className="w-3.5 h-3.5" />
                {activeDailyEntry.statusSemakan === 'disemak_guru'
                  ? 'Telah Disemak Guru'
                  : 'Tandakan Telah Disemak Guru'}
              </button>
            </div>
          )}

          {activeSlot ? (
            <RphDocumentPreview
              input={
                activeDailyEntry?.requestInput ?? {
                  mata_pelajaran: activeSlot.mata_pelajaran,
                  tingkatan_tahun: activeSlot.kelas,
                  kurikulum: activeSlot.kurikulum,
                  data_rpt_minggu: {
                    minggu: `Minggu ${activeMinggu}`,
                    tema: '',
                    standard_kandungan: '',
                    standard_pembelajaran: '',
                    catatan: '',
                  },
                  profil_kelas: {
                    bil_murid: '30 orang murid',
                    tahap_penguasaan_umum: 'TP3–TP4',
                    keperluan_khas_umum: '',
                  },
                  jadual: {
                    tarikh: selectedDate,
                    masa_mula: activeSlot.masa_mula,
                    masa_tamat: activeSlot.masa_tamat,
                    tempoh_minit: activeSlot.tempoh_minit,
                  },
                  sumber_ada: ['Papan putih & pen penanda', 'Buku teks KPM'],
                  templat_rph: workspace.automation.templatRph,
                  catatan_guru: '',
                }
              }
              draft={activeDailyEntry?.draft ?? null}
              teacherReflection={activeDailyEntry?.teacherReflection ?? ''}
              onTeacherReflectionChange={(val) =>
                void handleReflectionUpdate(val)
              }
              onDraftUpdate={(updated) => void handleDraftInlineUpdate(updated)}
              onSaveDraft={() => {
                if (activeDailyEntry) onSaveDraftToArchive(activeDailyEntry);
              }}
              onLoadSampleAndGenerate={() =>
                void onGenerateDaily({
                  date: selectedDate,
                  mingguNombor: activeMinggu,
                  forceRegenerate: true,
                  slotIds: [activeSlot.id],
                })
              }
              onFocusRptSection={onGoToSetup}
              isGenerating={isGeneratingDaily && !activeDailyEntry}
              errorMessage={null}
              schoolFormat={workspace.automation.schoolFormat}
            />
          ) : (
            <div className="bg-white border border-slate-200 rounded-xl p-8 text-center text-sm text-slate-500">
              Pilih hari persekolahan yang mempunyai jadual mengajar untuk
              melihat atau menjana draf RPH harian.
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
